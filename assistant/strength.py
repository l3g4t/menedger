"""
assistant.strength — общая логика оценки "силы" пароля по разнообразию
символов.

Используется и советником безопасности (assistant.advisor — чтобы
оценить уже существующие пароли в хранилище), и генератором
(assistant.generator — чтобы посчитать энтропию сгенерированного пароля
по ТОЙ ЖЕ формуле, что и сама генерация). Общий модуль исключает
рассинхронизацию логики между "мы так генерируем" и "мы так оцениваем".

ВАЖНОЕ ОГРАНИЧЕНИЕ (стоит проговорить на защите): это НЕ полноценный
анализ стойкости пароля вроде zxcvbn. Мы не детектируем произвольные
словарные слова или клавиатурные паттерны в общем виде — только
конкретный небольшой список самых частых паролей (COMMON_PASSWORDS) и
вхождение логина/сайта в сам пароль. Формула энтропии ниже предполагает,
что пароль — это НЕЗАВИСИМЫЕ СЛУЧАЙНЫЕ символы из своего алфавита; для
пароля, придуманного человеком (а не сгенерированного нами), это
ЗАВЫШЕННАЯ оценка — человек предсказуемее равномерного распределения
(закономерности, даты, имена). Поэтому оценка используется только как
грубая нижняя граница для советника, а не как гарантия стойкости.
"""

from __future__ import annotations

import math
import string

LOWERCASE = string.ascii_lowercase  # 26 символов
UPPERCASE = string.ascii_uppercase  # 26 символов
DIGITS = string.digits  # 10 символов
# Печатаемые спецсимволы, доступные почти на любой клавиатурной раскладке.
SYMBOLS = "!@#$%^&*()-_=+[]{};:,.<>?/"  # 30 символов

_KNOWN_CLASSES = (LOWERCASE, UPPERCASE, DIGITS, SYMBOLS)

# Небольшой список самых часто встречающихся паролей по открытым
# исследованиям утечек. Если пароль совпадает с одним из них (без учёта
# регистра) — это красный флаг НЕЗАВИСИМО от формальной энтропии по
# формуле ниже (например, "Password1" даёт неплохую формальную оценку,
# но остаётся одним из первых вариантов при переборе по словарю).
COMMON_PASSWORDS = frozenset(
    {
        "password", "123456", "12345678", "123456789", "qwerty", "111111",
        "123123", "abc123", "password1", "1234567890", "qwerty123",
        "admin", "letmein", "welcome", "monkey", "iloveyou", "dragon",
        "master", "1q2w3e4r", "sunshine", "princess", "football",
    }
)


def alphabet_size(password: str) -> int:
    """Оценить размер "алфавита", из которого предположительно выбран
    пароль, по тому, какие классы символов в нём встречаются.

    Например, пароль только из строчных букв — алфавит 26 символов;
    буквы + цифры + спецсимволы — 26+26+10+30 = 92 символа.
    """
    size = 0
    for char_class in _KNOWN_CLASSES:
        if any(ch in char_class for ch in password):
            size += len(char_class)

    known = "".join(_KNOWN_CLASSES)
    if any(ch not in known for ch in password):
        # Символы вне известных классов (например, не-ASCII) — считаем
        # консервативно, добавляя всего 1 к алфавиту за такой класс,
        # чтобы не переоценить силу пароля из экзотических символов.
        size += 1

    return max(size, 1)


def estimate_entropy_bits(password: str) -> float:
    """Грубая оценка энтропии пароля в битах: длина * log2(размер алфавита).

    См. ограничения формулы в docstring модуля — это оценка для
    равномерно-случайного выбора символов, не анализ смысла пароля.
    """
    if not password:
        return 0.0
    return len(password) * math.log2(alphabet_size(password))


def is_common_password(password: str) -> bool:
    """Проверить пароль по небольшому списку самых частых утёкших паролей."""
    return password.lower() in COMMON_PASSWORDS
