"""
assistant.offline — ответы помощника БЕЗ модели (CLAUDE.md, раздел 9.4).

Нужны, пока файл модели `.gguf` не скачан (или слишком слабый компьютер):
чат всё равно отвечает на типовые вопросы, подставляя числа из отчёта
советника. Это не «искусственный интеллект», а набор шаблонов по
ключевым словам — в интерфейсе такие ответы помечаются.
"""

from __future__ import annotations

from .prompt import AssistantContext

_HELP = (
    "Я отвечаю на вопросы про безопасность паролей: как придумать надёжный "
    "пароль, что значат слабые, повторяющиеся и устаревшие пароли, зачем "
    "нужен мастер-пароль. Спросите, например: «что со слабыми паролями?»."
)


def _sites(sites: list[str]) -> str:
    return ", ".join(sites)


def _plural(n: int, forms: tuple[str, str, str]) -> str:
    """1 запись, 2 записи, 5 записей."""
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return forms[0]
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return forms[1]
    return forms[2]


def _priority(ctx: AssistantContext) -> str:
    if ctx.reused_count:
        text = (
            f"Начните с повторяющихся паролей ({_sites(ctx.reused_sites)}): они опаснее всего, "
            "ведь утечка одного сайта открывает сразу несколько."
        )
        if ctx.weak_count:
            text += f" Затем замените слабые ({_sites(ctx.weak_sites)})"
            text += f", потом обновите старые ({_sites(ctx.old_sites)})." if ctx.old_count else "."
        elif ctx.old_count:
            text += f" Потом обновите старые ({_sites(ctx.old_sites)})."
        return text
    if ctx.weak_count:
        text = f"Начните со слабых паролей ({_sites(ctx.weak_sites)}): их легче всего подобрать."
        if ctx.old_count:
            text += f" Потом обновите старые ({_sites(ctx.old_sites)})."
        return text
    if ctx.old_count:
        return f"Обновите давно не менявшиеся пароли ({_sites(ctx.old_sites)}), начиная с самых важных аккаунтов."
    return "Явных проблем нет: советник ничего не нашёл. Включите двухфакторную аутентификацию для почты и банков."


def offline_answer(question: str, ctx: AssistantContext | None) -> str:
    q = question.lower()
    known = ctx is not None and ctx.unlocked

    # Пароль в вопросе (он уже скрыт, assistant.prompt.redact_secrets) или
    # просьба показать/назвать пароль — отвечаем про безопасность, а не по теме.
    if "[пароль скрыт]" in q:
        return (
            "Я не вижу и не оцениваю конкретные пароли, и вам не стоит присылать их в чат. "
            "Если пароль уже где-то оказался, смените его на сгенерированный."
        )
    if any(w in q for w in ("покажи", "назови", "какой у меня пароль", "мои пароли")):
        return (
            "Я не вижу паролей и мастер-пароля — они доступны только вам. Откройте запись в "
            "списке двойным щелчком и нажмите значок копирования."
        )
    if known and any(w in q for w in ("первую очередь", "с чего начать", "что исправ", "что делать", "что поменя")):
        return _priority(ctx)
    if known and any(w in q for w in ("в порядке", "всё ли", "все ли", "как дела", "как мои пароли")):
        problems = ctx.reused_count + ctx.weak_count + ctx.old_count
        if not problems:
            return f"Да, советник проблем не нашёл: в хранилище {ctx.total_entries} {_plural(ctx.total_entries, ('запись', 'записи', 'записей'))}, повторов, слабых и устаревших паролей нет."
        return f"Не совсем: найдено проблем — {problems}. " + _priority(ctx)

    if any(w in q for w in ("повтор", "одинаков", "один и тот же")):
        if known and ctx.reused_count:
            return (
                f"Одинаковый пароль на нескольких сайтах: групп — {ctx.reused_count} "
                f"({_sites(ctx.reused_sites)}). Если один сайт утечёт, злоумышленник "
                "попробует тот же пароль на остальных. Сделайте для каждого сайта свой "
                "пароль — генератор в приложении сделает это за секунду."
            )
        return (
            "Повторяющихся паролей в хранилище нет. Так и оставляйте: у каждого сайта "
            "должен быть свой пароль, тогда утечка одного не откроет остальные."
        )
    if any(w in q for w in ("слаб", "ненадёжн", "ненадежн", "простой пароль")):
        if known and ctx.weak_count:
            return (
                f"Слабых паролей: {ctx.weak_count} ({_sites(ctx.weak_sites)}). "
                "Это частые пароли, пароли с логином или названием сайта внутри либо "
                "слишком короткие. Замените их на сгенерированные длиной от 16 символов."
            )
        return "Слабых паролей советник не нашёл. Для новых используйте генератор, длина от 16 символов."
    if any(w in q for w in ("стар", "устарев", "давно", "менять", "сменить")):
        if known and ctx.old_count:
            return (
                f"Не менялись больше полугода: {ctx.old_count} ({_sites(ctx.old_sites)}). "
                "Для важных аккаунтов (почта, банк) пароль стоит менять хотя бы раз в год "
                "и сразу после любой утечки на этом сайте."
            )
        return "Устаревших паролей нет. Меняйте важные пароли после утечек и хотя бы раз в год."
    if "мастер" in q:
        return (
            "Мастер-пароль защищает всё хранилище, поэтому он должен быть длинным: лучше "
            "фраза из 4–5 случайных слов (от 20 символов), которую вы запомните сами. "
            "Нигде его не записывайте и не используйте на других сайтах. Если его забыть, "
            "восстановить хранилище нельзя."
        )
    if any(w in q for w in ("надёжн", "надежн", "придум", "сложн", "создать пароль", "как сделать пароль", "длин")):
        return (
            "Надёжный пароль — длинный и случайный: от 16 символов, с буквами обеих "
            "регистров, цифрами и символами, и свой для каждого сайта. Не используйте "
            "имена, даты и слова из словаря. Проще всего взять пароль из генератора и "
            "хранить в менеджере."
        )
    if any(w in q for w in ("безопасн", "шифр", "защищ", "взлом", "украд")):
        return (
            "Хранилище шифруется AES-256-GCM, ключ получается из мастер-пароля через "
            "Argon2id — перебор пароля намеренно медленный и требует много памяти. "
            "Всё хранится только в файле на вашем компьютере, в сеть ничего не уходит."
        )
    if any(w in q for w in ("двухфактор", "2fa", "двух фактор", "код из смс")):
        return (
            "Двухфакторная аутентификация добавляет второй шаг входа (код из приложения). "
            "Включите её хотя бы для почты и банков: даже при утечке пароля войти без "
            "второго фактора не получится."
        )
    if any(w in q for w in ("фишинг", "поддельн", "ссылк")):
        return (
            "Фишинг — поддельный сайт, который просит ввести пароль. Проверяйте адрес "
            "в строке браузера и не переходите по ссылкам из писем про «блокировку»; "
            "менеджер паролей не подставит пароль на чужой адрес."
        )
    if any(w in q for w in ("привет", "здравств", "что умеешь", "помощь", "помоги")):
        return _HELP
    if known and ctx.total_entries:
        problems = ctx.reused_count + ctx.weak_count + ctx.old_count
        return (
            f"В хранилище {ctx.total_entries} {_plural(ctx.total_entries, ('запись', 'записи', 'записей'))}, проблем найдено: {problems} "
            f"(повторы — {ctx.reused_count}, слабые — {ctx.weak_count}, устаревшие — "
            f"{ctx.old_count}). " + _HELP
        )
    return _HELP
