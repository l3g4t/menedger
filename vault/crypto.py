"""
vault.crypto — криптографическое ядро менеджера паролей.

Здесь реализованы все крипто-примитивы, на которых строится хранилище:
вывод ключа из мастер-пароля (Argon2id) и симметричное аутентифицированное
шифрование данных (AES-256-GCM). Полное обоснование каждого решения —
в CLAUDE.md (разделы 2 "Технологический стек" и 3 "Формат файла
хранилища"); комментарии здесь дают краткую версию рядом с конкретным
кодом, чтобы не листать документ туда-обратно при чтении реализации.
"""

from __future__ import annotations

import json
import os

from argon2.low_level import Type, hash_secret_raw
from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# === Формат бинарного файла хранилища ===================================
# MAGIC(4) || VERSION(1) || SALT(16) || NONCE(12) || CIPHERTEXT(остаток)
# Подробности — CLAUDE.md, раздел 3.

MAGIC = b"PMGR"        # 4 байта — быстрая проверка "это точно наш формат"
VERSION = 1            # 1 байт — номер версии формата, для будущих миграций

SALT_SIZE = 16         # соль для Argon2id. 16 байт — с запасом больше
                       # минимума, который требует сам Argon2id (8 байт),
                       # чтобы соль была практически гарантированно уникальна
                       # для каждого создаваемого хранилища.
NONCE_SIZE = 12        # стандартный и самый эффективный размер nonce для
                       # AES-GCM, рекомендованный NIST SP 800-38D.
KEY_SIZE = 32          # 32 байта = 256 бит — размер ключа для AES-256.

# Константа-маркер, которую мы добавляем внутрь зашифрованного JSON и
# сверяем после расшифровки. Она НЕ хранится отдельно от зашифрованных
# данных и не участвует в выводе ключа — единственный секрет в системе
# это сам мастер-пароль. Подробнее — CLAUDE.md, раздел 3, "Почему проверка
# мастер-пароля не требует отдельного хеша".
CANARY = "PMGR-OK"

# === Параметры Argon2id ===================================================
# Обоснование выбора Argon2id (а не PBKDF2/Argon2i/Argon2d) — CLAUDE.md,
# раздел 2. Сами числовые параметры взяты с запасом относительно
# минимальных рекомендаций OWASP (m=19 MiB, t=2, p=1): вывод ключа
# выполняется редко — один раз при открытии хранилища, а не на каждый
# запрос — поэтому можем позволить себе более медленный и "дорогой по
# памяти" вариант ради устойчивости к офлайн-перебору пароля.
ARGON2_TIME_COST = 3          # число проходов по памяти
ARGON2_MEMORY_COST = 65536    # 64 MiB (значение в килобайтах для argon2-cffi)
ARGON2_PARALLELISM = 4        # число потоков вычисления

# ВАЖНО: если эти параметры когда-либо изменятся, старые хранилища
# перестанут открываться существующим кодом (другие параметры → другой
# ключ для того же пароля и той же соли). Смена параметров должна идти
# вместе с повышением VERSION и написанием миграции — см. CLAUDE.md.


class InvalidMasterPasswordError(Exception):
    """Мастер-пароль неверен — либо содержимое хранилища повреждено/подделано.

    Мы намеренно НЕ различаем эти два случая одним и тем же типом
    исключения на публичном API: не даём потенциальному атакующему
    дополнительную информацию через разницу в поведении программы
    (см. CLAUDE.md, раздел 4).
    """


class VaultFormatError(Exception):
    """Файл не похож на хранилище нашего формата (неверный MAGIC/VERSION)."""


def derive_key(master_password: str, salt: bytes) -> bytes:
    """Вывести 256-битный ключ шифрования из мастер-пароля через Argon2id.

    Один и тот же (master_password, salt) при одних и тех же параметрах
    Argon2id всегда дают один и тот же ключ — на этом строится вся схема:
    при расшифровке соль читается из файла хранилища, и с её помощью
    заново выводится ровно тот ключ, что использовался при шифровании.

    Аргументы:
        master_password: мастер-пароль пользователя в виде строки.
        salt: соль, ровно SALT_SIZE байт (для нового хранилища — случайная,
            для существующего — прочитанная из файла).

    Возвращает:
        KEY_SIZE байт — сырой ключевой материал для AES-256-GCM.
    """
    if len(salt) != SALT_SIZE:
        raise ValueError(f"salt должен быть {SALT_SIZE} байт, получено {len(salt)}")

    return hash_secret_raw(
        secret=master_password.encode("utf-8"),
        salt=salt,
        time_cost=ARGON2_TIME_COST,
        memory_cost=ARGON2_MEMORY_COST,
        parallelism=ARGON2_PARALLELISM,
        hash_len=KEY_SIZE,
        # Type.ID — это и есть Argon2id (гибрид Argon2i + Argon2d).
        # Почему id, а не i или d по отдельности — см. CLAUDE.md, раздел 2.
        type=Type.ID,
    )


def encrypt_vault(data: dict, master_password: str) -> bytes:
    """Зашифровать данные хранилища и собрать итоговый бинарный blob.

    Каждый вызов заново генерирует случайные соль и nonce — даже если
    шифруются те же самые данные с тем же мастер-паролем, результат на
    диске будет другим. Это не баг, а обязательное требование безопасности:
    переиспользование пары (ключ, nonce) в AES-GCM катастрофически ломает
    шифрование (см. CLAUDE.md, раздел 3, "Почему nonce обязан быть
    уникальным"), поэтому соль (а значит и производный ключ) тоже
    обновляется при каждом сохранении хранилища — так проще гарантировать
    уникальность nonce, не полагаясь на память о "какие nonce уже
    использовались с этим ключом".

    Аргументы:
        data: словарь с данными хранилища, например {"entries": [...]}.
            Не должен содержать ключ "canary" — он будет добавлен здесь.
        master_password: мастер-пароль пользователя.

    Возвращает:
        Готовый к записи на диск blob:
        MAGIC || VERSION || SALT || NONCE || CIPHERTEXT.
    """
    salt = os.urandom(SALT_SIZE)
    nonce = os.urandom(NONCE_SIZE)

    key = derive_key(master_password, salt)

    # Добавляем canary внутрь данных ДО сериализации — она будет
    # зашифрована и аутентифицирована вместе со всем остальным JSON.
    payload = dict(data)
    payload["canary"] = CANARY
    plaintext = json.dumps(payload, ensure_ascii=False).encode("utf-8")

    # AESGCM.encrypt() сама дописывает 16-байтный auth tag в конец
    # ciphertext — это и есть механизм AEAD, который защищает не только
    # конфиденциальность, но и целостность/подлинность данных: при
    # расшифровке с неверным ключом или подменённым ciphertext тег не
    # совпадёт, и cryptography бросит InvalidTag (см. decrypt_vault).
    # associated_data=None: нам не нужно аутентифицировать ничего сверх
    # самого JSON (в отличие от, например, версии протокола, которую можно
    # было бы передать как AAD — но у нас версия уже "заморожена" в MAGIC
    # снаружи ciphertext и меняется только вместе со сменой всего формата).
    aesgcm = AESGCM(key)
    ciphertext = aesgcm.encrypt(nonce, plaintext, associated_data=None)

    return MAGIC + bytes([VERSION]) + salt + nonce + ciphertext


def decrypt_vault(blob: bytes, master_password: str) -> dict:
    """Разобрать бинарный blob хранилища и расшифровать данные.

    Выполняет два независимых уровня проверки мастер-пароля
    (см. CLAUDE.md, раздел 4 "Обработка неверного мастер-пароля"):

        1. AES-GCM auth tag — библиотека cryptography бросает InvalidTag,
           если производный ключ (а значит, и мастер-пароль) неверен,
           либо ciphertext был изменён хотя бы на 1 байт после шифрования.
        2. Проверка canary-строки внутри уже расшифрованного JSON —
           дополнительная защита на случай, если тег каким-то образом
           совпал (или в будущем формат данных изменится не так, как
           ожидает эта проверка).

    Аргументы:
        blob: сырые байты файла хранилища.
        master_password: мастер-пароль, который пробуем проверить.

    Возвращает:
        Исходный словарь data, переданный в encrypt_vault (без ключа
        "canary" — он служебный и наружу не отдаётся).

    Исключения:
        VaultFormatError: blob не похож на файл нашего формата вообще
            (слишком короткий, неверная сигнатура, незнакомая версия).
            Это НЕ связано с мастер-паролем — сигнализирует, что это,
            например, вообще не тот файл.
        InvalidMasterPasswordError: формат файла в порядке, но пароль
            неверен (или содержимое повреждено/подделано — см. класс).
    """
    header_size = len(MAGIC) + 1 + SALT_SIZE + NONCE_SIZE
    if len(blob) < header_size:
        raise VaultFormatError("файл слишком короткий для формата хранилища")

    magic = blob[:4]
    version = blob[4]
    salt = blob[5:21]
    nonce = blob[21:33]
    ciphertext = blob[33:]

    if magic != MAGIC:
        raise VaultFormatError("неверная сигнатура файла (ожидался MAGIC=PMGR)")
    if version != VERSION:
        raise VaultFormatError(f"неподдерживаемая версия формата хранилища: {version}")

    key = derive_key(master_password, salt)
    aesgcm = AESGCM(key)

    try:
        plaintext = aesgcm.decrypt(nonce, ciphertext, associated_data=None)
    except InvalidTag as exc:
        # AES-GCM не различает "неверный ключ" и "подделанный ciphertext" —
        # в обоих случаях auth tag не сойдётся. Это нормально и ожидаемо:
        # секретность и целостность здесь обеспечивает именно ключ
        # (то есть мастер-пароль), а не какое-либо доверие к файлу на диске.
        raise InvalidMasterPasswordError("неверный мастер-пароль") from exc

    try:
        payload = json.loads(plaintext.decode("utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        # Практически недостижимо после успешной проверки auth tag (тег
        # длиной 128 бит делает случайное совпадение при неверном ключе
        # исчезающе маловероятным), но проверяем как защиту в глубину —
        # на случай ошибок в будущих версиях формата.
        raise InvalidMasterPasswordError("неверный мастер-пароль") from exc

    if not isinstance(payload, dict) or payload.get("canary") != CANARY:
        raise InvalidMasterPasswordError("неверный мастер-пароль")

    del payload["canary"]
    return payload
