"""
vault.storage — чтение и атомарная запись файла хранилища на диске.

Модуль ничего не знает о шифровании: он работает с уже готовыми "сырыми"
байтами — тем, что возвращает vault.crypto.encrypt_vault, и тем, что
нужно передать в vault.crypto.decrypt_vault. Такое разделение
ответственности позволяет тестировать крипто-логику и файловый I/O
независимо друг от друга.

Обоснование схемы атомарной записи — CLAUDE.md, раздел 5
("Атомарная запись хранилища").
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path


def load_vault_file(path: str | os.PathLike) -> bytes:
    """Прочитать сырые байты файла хранилища (без расшифровки).

    Стандартные исключения файловой системы (FileNotFoundError,
    PermissionError и т.п.) пробрасываются как есть — решать, как
    показать их пользователю, дело вызывающего кода (CLI).
    """
    return Path(path).read_bytes()


def save_vault_file(path: str | os.PathLike, blob: bytes) -> None:
    """Атомарно записать байты хранилища на диск.

    Реализует схему из CLAUDE.md, раздел 5:

        1. Пишем blob во временный файл РЯДОМ с целевым — в той же
           директории. Это важно: os.replace() атомарен только внутри
           одной файловой системы, а /tmp почти всегда смонтирован
           отдельно от рабочей директории пользователя.
        2. flush() + os.fsync() временного файла — данные гарантированно
           уходят на физический носитель, а не остаются в буфере ОС.
           Без этого шага os.replace() ниже мог бы атомарно подставить
           файл, чьё содержимое ещё не пережило бы отключение питания.
        3. os.replace(tmp, path) — а не os.rename(): replace() атомарно
           заменяет целевой файл, даже если он уже существует (в отличие
           от rename(), который на Windows падает с ошибкой, если
           назначение уже занято). На POSIX и Windows это гарантированно
           атомарная операция: в любой момент времени файл по целевому
           пути либо старый целиком, либо новый целиком.

    Если что-то пойдёт не так до шага 3 (ошибка записи, нехватка места
    на диске и т.п.), временный файл удаляется, а целевой файл остаётся
    полностью нетронутым — промежуточного "битого" состояния не бывает.
    """
    target = Path(path)
    # Создаём (при необходимости) директорию назначения и в ней же —
    # временный файл. dir=directory обязателен: без него tempfile
    # положил бы файл в системный /tmp, откуда os.replace() на целевой
    # путь может оказаться межфайловой операцией (не атомарной или
    # вовсе невозможной, если это разные разделы/диски).
    directory = target.parent if str(target.parent) else Path(".")
    directory.mkdir(parents=True, exist_ok=True)

    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{target.name}.", suffix=".tmp", dir=directory
    )
    tmp_path = Path(tmp_name)

    try:
        with os.fdopen(fd, "wb") as tmp_file:
            tmp_file.write(blob)
            tmp_file.flush()
            os.fsync(tmp_file.fileno())

        os.replace(tmp_path, target)
    except BaseException:
        # Не дошли до os.replace() — подчищаем за собой временный файл.
        # Целевой файл в этой ветке никак не затрагивался.
        tmp_path.unlink(missing_ok=True)
        raise

    # Сама операция os.replace() — это тоже запись, но уже в метаданные
    # директории (какое имя на какой inode теперь указывает), и она
    # может ненадолго задержаться в буфере ОС. fsync директории —
    # дополнительная гарантия того, что после сбоя сразу после успешного
    # save_vault_file() каталог не "забудет" про переименование.
    _fsync_directory(directory)


def _fsync_directory(directory: Path) -> None:
    """Досинхронизировать саму директорию после os.replace().

    На Windows открыть директорию через os.open() нельзя (и в этом нет
    необходимости — семантика файловой системы там другая), поэтому шаг
    просто пропускается.
    """
    if os.name == "nt":
        return

    dir_fd = os.open(directory, os.O_RDONLY)
    try:
        os.fsync(dir_fd)
    finally:
        os.close(dir_fd)
